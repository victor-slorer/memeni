// Merges topic decks (schema-1 Markdown) into one file. Kept dependency-free so
// scripts/merge-decks.ts can run it directly with Node's type stripping.

export interface DeckFile {
  name: string;
  text: string;
}

/** The card blocks of one Markdown deck: each starts at a `### ` heading outside a code fence. */
export function splitCards(text: string): string[] {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  let i = 0;
  if (lines[0]?.trim() === '---') {
    i = 1;
    while (i < lines.length && lines[i].trim() !== '---') i++;
    i++;
  }
  const cards: string[][] = [];
  let inFence = false;
  for (; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
    if (!inFence && line.startsWith('### ')) cards.push([]);
    cards.at(-1)?.push(line);
  }
  return cards.map((c) => c.join('\n').trimEnd());
}

/** Round-robin across decks (sorted by name), so topics are interleaved even in file order. */
export function mergeDecks(decks: readonly DeckFile[]): string {
  const sorted = [...decks].sort((a, b) => a.name.localeCompare(b.name));
  const queues = sorted.map((d) => splitCards(d.text));
  const out: string[] = [];
  for (let round = 0; queues.some((q) => round < q.length); round++) {
    for (const q of queues) if (round < q.length) out.push(q[round]);
  }
  const header = [
    '---',
    'schema: 1',
    'topic: all',
    `generated-from: ${sorted.map((d) => d.name).join(', ')}`,
    'note: generated by `npm run decks:merge`; edit the topic files instead',
    '---',
  ].join('\n');
  return `${header}\n\n${out.join('\n\n')}\n`;
}
